package com.northstar.claims.tests.transcript;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.northstar.claims.tests.support.SnapshotDatabaseTest;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import org.springframework.boot.test.web.server.LocalServerPort;
import static org.junit.jupiter.api.Assertions.assertAll;
import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * Replays one committed transcript the way parity/replay.py does: restore the scenario's
 * legacy snapshot, open a fresh session (login first unless the scenario is login), send
 * the transcript request, run its db_state probes in the same session and compare.
 */
public abstract class TranscriptReplayTest extends SnapshotDatabaseTest {
    private static final ObjectMapper JSON = new ObjectMapper();
    /** Committed legacy fixtures (read-only; never regenerated by these tests). */
    static final Path TRANSCRIPTS = Path.of("..", "transcripts");

    @LocalServerPort
    int port;

    protected void replay(String scenario) throws Exception {
        JsonNode transcript = JSON.readTree(TRANSCRIPTS.resolve(scenario + ".json").toFile());
        JsonNode request = transcript.get("request");
        JsonNode expected = transcript.get("expected");
        Map<String, String> form = JSON.convertValue(request.get("form"), new TypeReference<LinkedHashMap<String, String>>() {});

        restoreSnapshot(scenario);
        TranscriptClient client = new TranscriptClient("http://localhost:" + port)
                .openSession(!"login".equals(scenario));
        TranscriptClient.Response response = client.request(
                request.get("method").asText(), request.get("path").asText(), form);

        // Probe keys come from the transcript; the values are re-read through the app's pages.
        Map<String, String> expectedState = JSON.convertValue(expected.get("db_state"), new TypeReference<TreeMap<String, String>>() {});
        Map<String, String> actualState = new TreeMap<>();
        for (String key : expectedState.keySet()) {
            actualState.put(key, client.probe(key));
        }
        Map<String, String> expectedFields = JSON.convertValue(expected.get("business_fields"), new TypeReference<TreeMap<String, String>>() {});
        List<String> expectedErrors = JSON.convertValue(expected.get("validation_errors"), new TypeReference<List<String>>() {});

        assertAll(scenario,
                () -> assertEquals(expected.get("status").asInt(), response.status(), "status"),
                () -> assertEquals(expected.get("result").asText(),
                        TranscriptClient.result(response.body(), response.status(), response.location()), "result marker"),
                () -> assertEquals(expectedFields, TranscriptClient.fields(response.body()), "business_fields"),
                () -> assertEquals(expectedErrors, TranscriptClient.validationErrors(response.body()), "validation_errors"),
                () -> assertEquals(expectedState, actualState, "db_state"));
    }
}
