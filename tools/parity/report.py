"""Shared writer for parity/report.json and parity/report.md.

Each slice script (settlement_parity.py for 8083, payment_parity.py for 8084)
replays its own transcripts and hands its rows here. The writer merges them
with the rows of the other slices already in parity/report.json, so running
the scripts in either order leaves one report covering every slice, and
rewrites report.md from the merged rows. Neither output carries a revision or
a timestamp, so replaying the same scenarios against the same services
rewrites the same bytes.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REPORT_JSON = os.path.join(ROOT, "parity", "report.json")
REPORT_MD = os.path.join(ROOT, "parity", "report.md")

# Slices in the order their rows appear in the report, and the ADR that
# defines parity for each.
SLICES = [
    ("settlement_", "ADR-001", "docs/decisions/ADR-001-settlement-boundary.md:82-90", 8083),
    ("payment_", "ADR-002", "docs/decisions/ADR-002-payment-boundary.md", 8084),
]


def slice_index(scenario):
    for index, (prefix, unused, unused2, unused3) in enumerate(SLICES):
        if scenario.startswith(prefix):
            return index
    return len(SLICES)


def existing_rows():
    if not os.path.exists(REPORT_JSON):
        return []
    with open(REPORT_JSON) as handle:
        return json.load(handle).get("scenarios", [])


def write(prefix, rows):
    """Replace the rows of one slice (scenarios starting with ``prefix``) and
    rewrite both report files from the merged list. Rows keep the order their
    slice script produced; slices keep the order of ``SLICES``.

    Rows of the other slices are carried over from the existing report, so a
    script run on its own refreshes only its slice. ``make parity`` deletes the
    report before running every script, so its output never carries rows over.
    """
    merged = [row for row in existing_rows() if not row["scenario"].startswith(prefix)]
    merged += rows
    merged.sort(key=lambda row: slice_index(row["scenario"]))
    os.makedirs(os.path.dirname(REPORT_JSON), exist_ok=True)
    with open(REPORT_JSON, "w") as handle:
        json.dump({"scenarios": merged}, handle, indent=2, sort_keys=True)
        handle.write("\n")
    with open(REPORT_MD, "w") as handle:
        handle.write("# Parity\n\n")
        handle.write("Generated by `make parity` (tools/parity/settlement_parity.py and\n")
        handle.write("tools/parity/payment_parity.py); the same verdicts are in parity/report.json.\n")
        handle.write("Each row replays a `transcripts/settlement_*.json` scenario against the\n")
        handle.write("settlement service on 8083, or a `transcripts/payment_*.json` scenario\n")
        handle.write("against the payment service on 8084, and compares the four things\n")
        handle.write("ADR-001:82-90 and ADR-002 (\"How parity is judged\") call parity: status\n")
        handle.write("class, business fields, validation keys, db state.\n\n")
        handle.write("Scenarios listed in `parity/routes.json` are approved differences: they\n")
        handle.write("are judged against their `docs/changes/CHG-nnn` record and reported as\n")
        handle.write("CHANGED, and still fail on anything the record does not approve. The\n")
        handle.write("payment slice allows none (ADR-002, \"Behaviour freeze\").\n\n")
        handle.write("| Scenario | Legacy behaviour | Verdict | Difference |\n")
        handle.write("| --- | --- | --- | --- |\n")
        for row in merged:
            handle.write("| `%s` | %s | %s | %s |\n" % (
                row["scenario"], row["description"], row["verdict"], row["difference"]))
        handle.write("\nStatus class: the legacy error path forwards to `error.jsp` with a 200;\n")
        handle.write("ADR-001:51,84 and ADR-002 replace that forward with the equivalent error\n")
        handle.write("status class, so a 5xx there is parity, not a change.\n")
