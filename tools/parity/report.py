#!/usr/bin/env python3
"""Write the parity verdicts of every slice: report.json, report.md, report.html.

Each slice runner (tools/parity/settlement_parity.py, payment_parity.py)
replaces its own rows with ``write_slice`` and leaves the other slices' rows as
they are, so ``make parity`` can run the runners one after the other.
Settlement rows keep their original keys (no ``slice`` key) so their lines in
report.json and report.md do not move when another slice is added.

report.html is the interactive twin of report.md: one self-contained file
(no network, no external scripts, fonts or images) built from
tools/parity/report_template.html with the verdicts embedded as JSON. Its
header shows, per slice, the rules with at least one scenario over the
rules of the slice's spec, and every verdict carries an Automated or
Reviewer mark. Never hand-edit it; ``make parity`` regenerates it.
"""

import glob
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import traceability  # noqa: E402

PARITY = os.path.join(ROOT, "parity")
SLICES = [
    {"slice": "settlement", "prefix": "SETTLE", "spec": "docs/specs/SPEC-SETTLE-001.md",
     "adr": "docs/decisions/ADR-001-settlement-boundary.md", "service": "settlement service on 8083"},
    {"slice": "payment", "prefix": "PAY", "spec": "docs/specs/SPEC-PAY-001.md",
     "adr": "docs/decisions/ADR-002-payment-boundary.md", "service": "payment service on 8084"},
]
SETTLEMENT_EQUIVALENCE = ("ADR-001:51,84: the legacy error.jsp forward (200) is answered "
                          "by the equivalent 5xx status class")


def slice_of(row):
    return row.get("slice", "settlement")


def load():
    path = os.path.join(PARITY, "report.json")
    if not os.path.exists(path):
        return []
    with open(path) as handle:
        return json.load(handle)["scenarios"]


def write_slice(name, rows):
    kept = [row for row in load() if slice_of(row) != name]
    order = [s["slice"] for s in SLICES]
    merged = sorted(kept + rows, key=lambda row: order.index(slice_of(row)))
    os.makedirs(PARITY, exist_ok=True)
    with open(os.path.join(PARITY, "report.json"), "w") as handle:
        json.dump({"scenarios": merged}, handle, indent=2, sort_keys=True)
        handle.write("\n")
    with open(os.path.join(PARITY, "report.md"), "w") as handle:
        handle.write(markdown(merged))
    with open(os.path.join(PARITY, "report.html"), "w") as handle:
        handle.write(page(merged))


def md_cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def markdown(rows):
    settlement = [row for row in rows if slice_of(row) == "settlement"]
    payment = [row for row in rows if slice_of(row) == "payment"]
    out = []
    out.append("# Settlement parity\n\n")
    out.append("Generated by `make parity` (tools/parity/settlement_parity.py); the same\n")
    out.append("verdicts are in parity/report.json.\n")
    out.append("Each row replays a `transcripts/settlement_*.json` scenario against the\n")
    out.append("settlement service on 8083 and compares the four things ADR-001:82-90\n")
    out.append("calls parity: status class, business fields, validation keys, db state.\n\n")
    out.append("Scenarios listed in `parity/routes.json` are approved differences: they\n")
    out.append("are judged against their `docs/changes/CHG-nnn` record and reported as\n")
    out.append("CHANGED, and still fail on anything the record does not approve.\n\n")
    out.append("| Scenario | Legacy behaviour | Verdict | Difference |\n")
    out.append("| --- | --- | --- | --- |\n")
    for row in settlement:
        out.append("| `%s` | %s | %s | %s |\n" % (
            row["scenario"], row["description"], row["verdict"], row["difference"]))
    out.append("\nStatus class: the legacy error path forwards to `error.jsp` with a 200;\n")
    out.append("ADR-001:51,84 replaces that forward with the equivalent error status\n")
    out.append("class, so a 5xx there is parity, not a change.\n")
    if payment:
        cov = coverage()["payment"]
        out.append("\n# Payment parity\n\n")
        out.append("Generated by `make parity` (tools/parity/payment_parity.py); the same\n")
        out.append("verdicts, with every step's expected and actual values, are in\n")
        out.append("parity/report.json and parity/report.html.\n")
        out.append("Each row resets the payment service on 8084 to the scenario's precondition\n")
        out.append("(`parity/preconditions/payment.sql`), replays the requests the legacy app\n")
        out.append("answered in `transcripts/payment_*.json` or `docs/specs/SPEC-PAY-001-proof.json`,\n")
        out.append("and compares what ADR-002 calls parity: status and redirect, screen,\n")
        out.append("field values in screen order, payee and method texts, links, operator,\n")
        out.append("validation keys and the database rows read afterwards.\n\n")
        out.append("Rule coverage: %d of %d SPEC-PAY-001 rule versions have a scenario.\n\n"
                   % (len(cov["covered"]), len(cov["rules"])))
        out.append("Check: *automated* means the service matched the legacy answer on every\n")
        out.append("compared item; *reviewer* means the verdict also rests on a recorded human\n")
        out.append("decision (a CHG record, or ADR-002's error-status equivalence).\n\n")
        out.append("| Scenario | Legacy behaviour | Rules | Precondition | Verdict | Check | Difference |\n")
        out.append("| --- | --- | --- | --- | --- | --- | --- |\n")
        for row in payment:
            out.append("| `%s` | %s | %s | %s | %s | %s | %s |\n" % (
                row["scenario"], md_cell(row["description"]),
                ", ".join(r.split(" ")[0] for r in row["rules"]),
                md_cell(row["precondition"]["name"]), row["verdict"], row["check"],
                md_cell(row["difference"])))
    return "".join(out)


def coverage():
    routes = json.load(open(os.path.join(PARITY, "routes.json")))
    result = {}
    for spec in SLICES:
        rules, unused = traceability.rules_and_history(spec["spec"])
        versions = ["%s (v%s)" % rule for rule in rules]
        scenarios = {}
        if spec["slice"] == "settlement":
            for name, cited in routes.get("transcript_rules", {}).items():
                if name.startswith("settlement_"):
                    for version, (rule, number) in zip(versions, rules):
                        if any(traceability.refers_to(entry, (rule, number)) for entry in cited):
                            scenarios.setdefault(version, []).append(name)
        else:
            for name, entry in routes.get("payment_scenarios", {}).items():
                for version in entry["rules"]:
                    scenarios.setdefault(version, []).append(name)
        result[spec["slice"]] = {"rules": versions,
                                 "covered": [v for v in versions if v in scenarios],
                                 "scenarios": scenarios}
    return result


def settlement_view(row):
    """The settlement row as the page shows it: transcript request and expected values."""
    transcript = json.load(open(os.path.join(ROOT, "transcripts", row["scenario"] + ".json")))
    expected = transcript["expected"]
    error = expected["result"].endswith("error.jsp")
    view = dict(row)
    view["slice"] = "settlement"
    view["source"] = "transcripts/%s.json" % row["scenario"]
    routes = json.load(open(os.path.join(PARITY, "routes.json")))
    view["rules"] = routes.get("transcript_rules", {}).get(row["scenario"], [])
    view["precondition"] = {"file": None, "name": "make capture order (ADR-001)", "sql": []}
    view["check"] = "reviewer" if row.get("change") or error else "automated"
    view["basis"] = ([row["change"] + ": " + row["record"]] if row.get("change") else []) + (
        [SETTLEMENT_EQUIVALENCE] if error and not row.get("change") else [])
    approved = next((e for e in routes.get("approved_differences", [])
                     if e["scenario"] == row["scenario"]), None)
    want = approved["expected"] if approved else expected
    view["steps"] = [{"n": 1, "request": transcript["request"], "actor": transcript.get("actor"),
                      "legacy": {"status": expected["status"], "result": expected["result"],
                                 "fields": expected["business_fields"],
                                 "validation_errors": expected["validation_errors"],
                                 "db_state": expected["db_state"]},
                      "service": None,
                      "checks": [{"what": k, "expected": want.get(k), "actual": "= expected",
                                  "ok": row["verdict"] != "FAIL", "basis": None}
                                 for k in ("status", "business_fields", "validation_errors", "db_state")
                                 if k in want]}]
    view["db"] = []
    return view


def page(rows):
    views = [settlement_view(row) if slice_of(row) == "settlement" else row for row in rows]
    cov = coverage()
    changes = {os.path.basename(p).split("-")[0] + "-" + os.path.basename(p).split("-")[1]:
               os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, "docs", "changes", "CHG-*.md"))}
    data = {"rows": views, "slices": SLICES, "coverage": cov, "changes": changes}
    text = json.dumps(data, sort_keys=True).replace("</", "<\\/")
    with open(os.path.join(ROOT, "tools", "parity", "report_template.html")) as handle:
        template = handle.read()
    return template.replace("@@DATA@@", text)


if __name__ == "__main__":
    rows = load()
    with open(os.path.join(PARITY, "report.md"), "w") as handle:
        handle.write(markdown(rows))
    with open(os.path.join(PARITY, "report.html"), "w") as handle:
        handle.write(page(rows))
