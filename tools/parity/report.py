"""Shared writer for parity/report.json, parity/report.md and parity/report.html.

Each slice script (settlement_parity.py for 8083, payment_parity.py for 8084)
replays its own scenarios and hands its rows here. The writer merges them with
the rows of the other slices already in parity/report.json, so running the
scripts in either order leaves one report covering every slice, and rewrites
report.md and report.html from the merged rows. No output carries a revision or
a timestamp, so replaying the same scenarios against the same services rewrites
the same bytes.

A row carries, besides its verdict, everything the HTML view opens on a click:
the request that was replayed, the precondition it was replayed under, the
expected and actual response and database state, and the rules it is evidence
for. report.html is one self-contained file with no network dependency.
"""

import html
