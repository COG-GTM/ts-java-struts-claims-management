ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REPORT_JSON = os.path.join(ROOT, "parity", "report.json")
REPORT_MD = os.path.join(ROOT, "parity", "report.md")
REPORT_HTML = os.path.join(ROOT, "parity", "report.html")

# Slices in the order their rows appear in the report, and the ADR that
# defines parity for each.
SLICES = [
    ("settlement_", "settlement", "ADR-001", "docs/decisions/ADR-001-settlement-boundary.md", 8083,
     "docs/specs/SPEC-SETTLE-001.md"),
    ("payment_", "payment", "ADR-002", "docs/decisions/ADR-002-payment-boundary.md", 8084,
     "docs/specs/SPEC-PAY-001.md"),
]


def slice_index(scenario):
    for index, entry in enumerate(SLICES):
        if scenario.startswith(entry[0]):
            return index
    return len(SLICES)


def existing_rows():
    if not os.path.exists(REPORT_JSON):
        return []
    with open(REPORT_JSON) as handle:
        return json.load(handle).get("scenarios", [])


def write(prefix, rows):
    """Replace the rows of one slice (scenarios starting with ``prefix``) and
    rewrite the three report files from the merged list. Rows keep the order
    their slice script produced; slices keep the order of ``SLICES``.

    Rows of the other slices are carried over from the existing report, so a
    script run on its own refreshes only its slice. ``make parity`` deletes the
    report before running every script, so its output never carries rows over.
    """
    merged = [row for row in existing_rows() if not row["scenario"].startswith(prefix)]
    merged += rows
    merged.sort(key=lambda row: slice_index(row["scenario"]))
    os.makedirs(os.path.dirname(REPORT_JSON), exist_ok=True)
    with open(REPORT_JSON, "w") as handle:
        json.dump({"scenarios": merged}, handle, indent=2, sort_keys=True, ensure_ascii=False)
        handle.write("\n")
    write_markdown(merged)
    write_html(merged)


def verdict_counts(rows):
    counts = {"PASS": 0, "CHANGED": 0, "FAIL": 0}
    for row in rows:
        counts[row["verdict"].split(" ")[0]] += 1
    return counts


def write_markdown(rows):
    counts = verdict_counts(rows)
    with open(REPORT_MD, "w") as handle:
        handle.write("# Parity\n\n")
        handle.write("Generated by `make parity` (tools/parity/settlement_parity.py and\n")
        handle.write("tools/parity/payment_parity.py through tools/parity/report.py); the same\n")
        handle.write("verdicts, with each scenario's request, precondition, expected and actual\n")
        handle.write("response and the rules it is evidence for, are in parity/report.json and\n")
        handle.write("the interactive parity/report.html.\n\n")
        handle.write("Each `settlement_*` row replays a `transcripts/settlement_*.json` scenario\n")
        handle.write("against the settlement service on 8083; each `payment_*` row replays a\n")
        handle.write("payment scenario of `parity/routes.json` (a `transcripts/payment_*.json`\n")
        handle.write("transcript, or a request recorded in `docs/specs/SPEC-PAY-001-live.json`)\n")
        handle.write("against the payment service on 8084 after applying the scenario's declared\n")
        handle.write("precondition from `parity/preconditions/payment`. Both compare the four\n")
        handle.write("things ADR-001:82-90 and ADR-002 (\"How parity is judged\") call parity:\n")
        handle.write("status class, business fields, validation keys, db state.\n\n")
        handle.write("Scenarios listed under `approved_differences` in `parity/routes.json` are\n")
        handle.write("judged against their `docs/changes/CHG-nnn` record and reported as CHANGED,\n")
        handle.write("and still fail on anything the record does not approve.\n\n")
        handle.write("%d scenarios: %d PASS, %d CHANGED, %d FAIL.\n\n" % (
            len(rows), counts["PASS"], counts["CHANGED"], counts["FAIL"]))
        handle.write("| Scenario | Legacy behaviour | Verdict | Difference |\n")
        handle.write("| --- | --- | --- | --- |\n")
        for row in rows:
            handle.write("| `%s` | %s | %s | %s |\n" % (
                row["scenario"], row["description"], row["verdict"], row["difference"]))
        handle.write("\nStatus class: the legacy error path forwards to `error.jsp` with a 200;\n")
        handle.write("ADR-001:51,84 and ADR-002 replace that forward with the equivalent error\n")
        handle.write("status class, so a 5xx there is parity, not a change.\n")


