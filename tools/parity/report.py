#!/usr/bin/env python3
"""Write the parity reports from the per-slice evidence.

Each replay tool (settlement_parity.py, payment_parity.py) writes what it sent,
what the legacy app did, what the service did and the checks it made to
``parity/evidence/<slice>.json``, then calls :func:`build`, which rewrites:

* ``parity/report.json`` — one verdict row per scenario, read by
  tools/traceability.py;
* ``parity/report.md`` — the verdict tables, settlement first;
* ``parity/report.html`` — the same verdicts as one self-contained page: a
  PASS/CHANGED table where a click on a scenario shows the request, expected
  against actual, and the rules it covers, with the rule text from
  docs/specs/SPEC-*.md.

None of them carries a revision, a path of this machine or a timestamp, so the
same evidence always gives the same bytes. Run directly to rebuild the three
reports from the committed evidence without any service running.
"""

import glob
import html
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PARITY = os.path.join(ROOT, "parity")
EVIDENCE = os.path.join(PARITY, "evidence")
SLICES = ["settlement", "payment"]
SUMMARY_KEYS = ["change", "description", "difference", "record", "scenario", "verdict"]

HEADING = re.compile(r"^\*\*([A-Z]+-R\d+) \(v(\d+)[^)]*\)\*\*\s*[—-]\s*(.*)$")


def check(name, expected, actual, ok):
    return {"name": name, "expected": expected, "actual": actual, "ok": bool(ok)}


def status_class(status):
    return "%dxx" % (status // 100) if status else "none"


def field_checks(expected, actual):
    checks = []
    for key in sorted(set(expected) | set(actual)):
        if key not in expected:
            checks.append(check("field " + key, "(no such field)", actual[key], False))
        else:
            checks.append(check("field " + key, expected[key], actual.get(key),
                                actual.get(key) == expected[key]))
    return checks


def write_evidence(slice_name, rows):
    os.makedirs(EVIDENCE, exist_ok=True)
    with open(os.path.join(EVIDENCE, slice_name + ".json"), "w") as handle:
        json.dump({"slice": slice_name, "scenarios": rows}, handle, indent=2, sort_keys=True)
        handle.write("\n")


def load(slice_name):
    path = os.path.join(EVIDENCE, slice_name + ".json")
    if not os.path.exists(path):
        return []
    with open(path) as handle:
        return json.load(handle)["scenarios"]


def rule_texts():
    """``{"ID (vN)": {"spec", "text"}}`` for every rule heading of every spec."""
    rules = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "docs", "specs", "SPEC-*.md"))):
        spec = os.path.basename(path)[: -len(".md")]
        with open(path, encoding="utf-8") as handle:
            lines = handle.read().splitlines()
        for index, line in enumerate(lines):
            match = HEADING.match(line)
            if not match:
                continue
            text = [match.group(3)]
            for following in lines[index + 1:]:
                if not following.strip() or following.startswith("Status:"):
                    break
                text.append(following.strip())
            key = "%s (v%s)" % (match.group(1), match.group(2))
            rules[key] = {"spec": spec, "text": " ".join(text)}
    return rules


def resolve(reference, rules):
    """A routes.json rule reference, versioned or not, to a rule key."""
    match = re.match(r"([A-Z]+-R\d+)(?:\s*\(v(\d+)\))?", reference)
    if not match:
        return reference
    if match.group(2):
        return "%s (v%s)" % (match.group(1), match.group(2))
    versions = sorted((int(k.split("(v")[1][:-1]), k) for k in rules
                      if k.startswith(match.group(1) + " "))
    return versions[-1][1] if versions else match.group(1)


def write_json(rows):
    with open(os.path.join(PARITY, "report.json"), "w") as handle:
        json.dump({"scenarios": [{k: row[k] for k in SUMMARY_KEYS} for row in rows]},
                  handle, indent=2, sort_keys=True)
        handle.write("\n")


def settlement_markdown(handle, rows):
    handle.write("# Settlement parity\n\n")
    handle.write("Generated by `make parity` (tools/parity/settlement_parity.py); the same\n")
    handle.write("verdicts are in parity/report.json.\n")
    handle.write("Each row replays a `transcripts/settlement_*.json` scenario against the\n")
    handle.write("settlement service on 8083 and compares the four things ADR-001:82-90\n")
    handle.write("calls parity: status class, business fields, validation keys, db state.\n\n")
    handle.write("Scenarios listed in `parity/routes.json` are approved differences: they\n")
    handle.write("are judged against their `docs/changes/CHG-nnn` record and reported as\n")
    handle.write("CHANGED, and still fail on anything the record does not approve.\n\n")
    handle.write("| Scenario | Legacy behaviour | Verdict | Difference |\n")
    handle.write("| --- | --- | --- | --- |\n")
    for row in rows:
        handle.write("| `%s` | %s | %s | %s |\n" % (
            row["scenario"], row["description"], row["verdict"], row["difference"]))
    handle.write("\nStatus class: the legacy error path forwards to `error.jsp` with a 200;\n")
    handle.write("ADR-001:51,84 replaces that forward with the equivalent error status\n")
    handle.write("class, so a 5xx there is parity, not a change.\n")


def payment_markdown(handle, rows):
    handle.write("# Payment parity\n\n")
    handle.write("Generated by `make payment-parity` (tools/parity/payment_parity.py); the\n")
    handle.write("same verdicts are in parity/report.json, and parity/report.html shows each\n")
    handle.write("scenario's request, expected against actual, and the rules it covers.\n")
    handle.write("Each row replays a payment transcript or a numbered live request of\n")
    handle.write("`docs/specs/SPEC-PAY-001-live.json` against the payment service on 8084\n")
    handle.write("and compares what ADR-002 (\"How parity is judged\") calls parity: status\n")
    handle.write("class and redirect target, business fields, validation keys, history\n")
    handle.write("links, payee and method as displayed, and database state.\n\n")
    handle.write("The live requests run in their recorded order from the seed. L02 and L35\n")
    handle.write("(sign in) and L05 (settlement save, applied as\n")
    handle.write("`parity/preconditions/payment/settlement-save.sql`) are setup, not\n")
    handle.write("scenarios. `payment_live_db_after` compares the database afterwards with\n")
    handle.write("the `db_after` queries of the live file.\n\n")
    handle.write("| Scenario | Legacy behaviour | Rules | Verdict | Difference |\n")
    handle.write("| --- | --- | --- | --- | --- |\n")
    for row in rows:
        handle.write("| `%s` | %s | %s | %s | %s |\n" % (
            row["scenario"], row["description"].replace("|", "\\|"),
            ", ".join(row["rules"]) or "-", row["verdict"], row["difference"].replace("|", "\\|")))


def write_markdown(by_slice):
    with open(os.path.join(PARITY, "report.md"), "w") as handle:
        first = True
        for slice_name, writer in (("settlement", settlement_markdown),
                                   ("payment", payment_markdown)):
            if not by_slice[slice_name]:
                continue
            if not first:
                handle.write("\n")
            writer(handle, by_slice[slice_name])
            first = False


def write_html(rows):
    rules = rule_texts()
    scenarios = []
    for row in rows:
        entry = dict(row)
        entry["rule_keys"] = [resolve(reference, rules) for reference in row.get("rules", [])]
        scenarios.append(entry)
    cited = sorted({key for entry in scenarios for key in entry["rule_keys"]})
    data = {"scenarios": scenarios, "rules": {key: rules[key] for key in cited if key in rules}}
    payload = json.dumps(data, indent=None, sort_keys=True, separators=(",", ":"))
    payload = payload.replace("</", "<\\/")
    with open(os.path.join(PARITY, "report.html"), "w") as handle:
        handle.write(TEMPLATE.replace("__DATA__", payload))


def build():
    by_slice = {name: load(name) for name in SLICES}
    rows = [row for name in SLICES for row in by_slice[name]]
    write_json(rows)
    write_markdown(by_slice)
    write_html(rows)


