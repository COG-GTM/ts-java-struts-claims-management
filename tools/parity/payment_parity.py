"""Replay the payment parity scenarios against the payment service.

Each scenario of ``parity/routes.json`` (``payment_scenarios``, generated by
tools/parity/payment_scenarios.py) names its database precondition, which is
applied with ``POST /parity/reset`` before the request is sent, so verdicts do
not depend on the order the scenarios run in. Parity is judged as ADR-002
("How parity is judged") states: status class, business fields as an exact
set, display texts and links, validation keys, and the PAYMENT rows from 61 up
(or the transcript's db_state keys). A difference is a FAIL unless
``approved_differences`` names the scenario with a CHG-nnn record, in which
case it is CHANGED. Verdicts go to parity/report.{json,md,html} through
tools/parity/report.py, next to the settlement rows.
"""
import argparse
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import report  # noqa: E402

ROOT = report.ROOT
LIVE = os.path.join(ROOT, "docs", "specs", "SPEC-PAY-001-live.json")


def load(path):
    with open(path) as handle:
        return json.load(handle)


def status_class(status):
    return "%dxx" % (status // 100)


def send(base, method, path, form=None, headers=None):
    data = urllib.parse.urlencode(form or {}).encode() if method == "POST" else None
    url = base + path
    if method == "GET" and form:
        url += "?" + urllib.parse.urlencode(form)
    req = urllib.request.Request(url, data=data, method=method)
    for key, value in (headers or {}).items():
        req.add_header(key, value)
    if method == "POST":
        req.add_header("Content-Type", "application/x-www-form-urlencoded")
    try:
        with urllib.request.urlopen(req) as response:
            return response.status, json.loads(response.read().decode())
    except urllib.error.HTTPError as error:
        return error.code, json.loads(error.read().decode())


def reset(base, precondition):
    status, body = send(base, "POST", "/parity/reset?precondition=" + precondition,
                        headers={"X-Parity-Reset": "1"})
    if status != 200:
        raise SystemExit("reset to %s failed: %s %s (is the service running with "
                         "--spring.profiles.active=parity, make payment-run-parity?)"
                         % (precondition, status, body))


def rows_from_61(base):
    status, body = send(base, "GET", "/parity/rows?minPaymentId=61")
    return body


def db_state(base, expected):
    """The transcripts' db_state keys, read back through the service's own screens:
    payment.<id>.amount / .status through /payment/detail (PaymentDAO.findById),
    payment.count.claim.<id> through remitCount of /payment/remittance
    (PaymentDAO.findByClaim)."""
    actual = {}
    for key in expected:
        parts = key.split(".")
        if parts[0] == "payment" and parts[1] == "count":
            _, body = send(base, "GET", "/payment/remittance", {"claimId": parts[3]})
            actual[key] = body["fields"]["remitCount"]
        elif parts[0] == "payment":
            _, body = send(base, "GET", "/payment/detail", {"paymentId": parts[1]})
            field = {"amount": "detailPaymentAmount", "status": "detailPaymentStatus"}[parts[2]]
            actual[key] = body["fields"][field]
        else:
            raise SystemExit("unknown db_state key %s" % key)
    return actual


def compare(expected, actual, keys):
    diffs = []
    for key in keys:
        if key not in expected:
            continue
        if expected[key] != actual.get(key):
            if isinstance(expected[key], dict):
                exp, act = expected[key], actual.get(key) or {}
                for name in sorted(exp.keys() | act.keys()):
                    if exp.get(name) != act.get(name):
                        diffs.append("%s.%s %r != %r" % (key, name, act.get(name), exp.get(name)))
            else:
                diffs.append("%s differs" % key)
    return diffs


def run(base, scenario, live_rows, approval):
    reset(base, scenario["precondition"])
    request = scenario["request"]
    status, body = send(base, request["method"], request["path"], request["form"])
    expected = dict(approval["expected"] if approval else scenario["expected"])
    actual = {
        "status": status,
        "screen": body.get("screen"),
        "business_fields": body.get("fields", {}),
        "validation_errors": body.get("errors", []),
    }
    diffs = []
    if status_class(status) != status_class(expected["status"]) and not (
            expected.get("result", "").endswith("error.jsp") and status >= 500):
        diffs.append("status class %s != %s" % (status_class(status), status_class(expected["status"])))
    if "display" in expected:
        actual["display"] = body.get("display", {})
    if "links" in expected:
        actual["links"] = body.get("links", [])
    if "db_state" in expected:
        actual["db_state"] = db_state(base, expected["db_state"])
    if "payment_rows_through" in expected:
        through = expected["payment_rows_through"]
        expected["payment_rows"] = [row for row in live_rows if 60 < int(row["payment_id"]) <= through]
        actual["payment_rows"] = rows_from_61(base)
    diffs += compare(expected, actual, ["business_fields", "display", "links",
                                        "validation_errors", "db_state", "payment_rows"])
    return diffs, expected, actual


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default=os.environ.get("PAYMENT_BASE", "http://localhost:8084"))
    args = parser.parse_args()
    routes = load(os.path.join(ROOT, "parity", "routes.json"))
    approvals = {entry["scenario"]: entry for entry in routes.get("approved_differences", [])}
    live_rows = load(LIVE)["db_after"]["payment_rows_after_seed"]["rows"]

    rows = []
    failed = False
    for scenario in routes["payment_scenarios"]:
        name = scenario["scenario"]
        approval = approvals.get(name)
        diffs, expected, actual = run(args.base, scenario, live_rows, approval)
        if approval:
            verdict = "CHANGED (%s)" % approval["change"] if not diffs else "FAIL"
            note = approval["summary"] if not diffs else "; ".join(diffs)
        else:
            verdict = "PASS" if not diffs else "FAIL"
            note = "; ".join(diffs) or "-"
        failed = failed or bool(diffs)
        rows.append({
            "slice": "payment",
            "scenario": name,
            "source": scenario["source"],
            "description": scenario["description"],
            "precondition": scenario["precondition"],
            "rules": scenario["rules"],
            "request": scenario["request"],
            "expected": expected,
            "actual": actual,
            "verdict": verdict,
            "change": approval["change"] if approval else None,
            "record": approval["record"] if approval else None,
            "difference": note,
        })
        print("%-28s %-22s %s %s" % (name, scenario["precondition"], verdict, "; ".join(diffs)))

    report.write("payment", rows)
    raise SystemExit(1 if failed else 0)


if __name__ == "__main__":
    main()
