"""Generated "Impact of CHG-nnn" block for a change record.

Everything in the block is read from the repository, not typed: the spec
headings and ``Approved:`` lines (rule versions the record introduces and the
versions they supersede), ``parity/routes.json`` and ``parity/report.json``
(the scenarios the record approves, with the verdict each had before the
record existed, taken from the parent of the commit that added the record),
the test javadocs that cite the record, the files changed by the record's
commits (first-parent history since the record was added), and a check that
the settlement rows of ``parity/report.json`` and ``docs/TRACEABILITY.md``,
``src/main`` and ``transcripts/`` are the same as before the record.

``update(record_path)`` rewrites the block between the ``impact:begin`` and
``impact:end`` markers of the record (appending it when absent) and returns
the data; ``build_change_html.py`` calls it before rendering the HTML twin.
"""
import glob
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import traceability  # noqa: E402

BEGIN = "<!-- impact:begin generated by tools/changes/impact.py; do not edit -->"
END = "<!-- impact:end -->"
HEADING = re.compile(r"^\*\*([A-Z]+-R\d+) \(v(\d+)(?:, superseded by v(\d+))?\)\*\*")
APPROVED = re.compile(r"^Approved: (\S+?)\.?$")
GENERATED = set(traceability.GENERATED) | {"docs/TRACEABILITY.md"}


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True,
                          capture_output=True, text=True).stdout


def git_ok(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True).returncode == 0


def show(commit, path):
    """A file at a commit, or None when it did not exist there."""
    result = subprocess.run(["git", "show", "%s:%s" % (commit, path)], cwd=ROOT,
                            capture_output=True, text=True)
    return result.stdout if result.returncode == 0 else None


def intro_commit(record_rel):
    commits = git("log", "--diff-filter=A", "--format=%H", "--", record_rel).split()
    return commits[-1] if commits else None


def rule_versions(record_rel):
    """Rule versions whose spec text names this record as their approval, and
    the superseded versions that point at them: PAY-R05 v1 -> v2."""
    touched = []
    for spec, _ in traceability.specs():
        blocks, current = [], None
        for line in traceability.read(spec).splitlines():
            match = HEADING.match(line)
            if match:
                current = {"rule": match.group(1), "version": match.group(2),
                           "superseded_by": match.group(3), "approved": None}
                blocks.append(current)
            elif current is not None:
                approved = APPROVED.match(line.strip())
                if approved:
                    current["approved"] = approved.group(1)
        for block in blocks:
            if block["approved"] != record_rel:
                continue
            previous = [b["version"] for b in blocks
                        if b["rule"] == block["rule"] and b["superseded_by"] == block["version"]]
            touched.append({"rule": block["rule"], "to": "v" + block["version"],
                            "from": ("v" + previous[0]) if previous else None, "spec": spec})
    return touched


def scenarios(record_rel, change, parent):
    with open(os.path.join(ROOT, "parity", "routes.json")) as handle:
        routes = json.load(handle)
    now = {row["scenario"]: row for row in json.loads(
        traceability.read(os.path.join("parity", "report.json")))["scenarios"]}
    before_text = show(parent, "parity/report.json") if parent else None
    before = ({row["scenario"]: row["verdict"] for row in json.loads(before_text)["scenarios"]}
              if before_text else {})
    rows = []
    for entry in routes.get("approved_differences", []):
        if entry.get("record") != record_rel:
            continue
        name = entry["scenario"]
        rows.append({"scenario": name,
                     "old": before.get(name, "not in the report (new scenario)"),
                     "new": now.get(name, {}).get("verdict", "not run"),
                     "source": "reviewer (%s)" % (entry.get("decision") or change),
                     "explicit": "request" in entry})
    return rows


def tests(change, parent):
    """Test methods whose javadoc cites the change id, and whether the method
    existed before the record (added or updated)."""
    found = []
    for path in sorted(traceability.test_files()):
        rel = os.path.relpath(path, ROOT)
        lines = traceability.read(rel).splitlines()
        old = show(parent, rel) if parent else None
        class_name = os.path.basename(path)[:-5]
        index = 0
        while index < len(lines):
            if lines[index].strip().startswith("/**"):
                block = []
                while index < len(lines):
                    block.append(lines[index])
                    if traceability.JAVADOC_END.search(lines[index]):
                        break
                    index += 1
                member = traceability.member_after(lines, index + 1)
                if member and re.search(r"\b%s\b" % re.escape(change), "\n".join(block)):
                    state = "added" if not old or not re.search(r"\b%s\s*\(" % member, old) else "updated"
                    found.append({"test": "%s#%s" % (class_name, member), "file": rel, "state": state})
            index += 1
    return found


def files_changed(parent):
    """Files touched by the record's own commits: first-parent history from the
    commit that added the record, merges excluded."""
    if not parent:
        return []
    commits = git("rev-list", "--first-parent", "--no-merges", "%s..HEAD" % parent).split()
    status = {}
    for commit in commits:
        for line in git("show", "--format=", "--name-status", commit).splitlines():
            parts = line.split("\t")
            if len(parts) >= 2:
                path = parts[-1]
                status.setdefault(path, parts[0][0])
    return [{"file": path, "status": {"A": "added", "M": "modified", "D": "deleted", "R": "renamed"}.get(code, code),
             "generated": path in GENERATED or any(glob.fnmatch.fnmatch(path, pattern)
                                                   for pattern in traceability.GENERATED_GLOBS)}
            for path, code in sorted(status.items())]


def untouched(parent):
    """What the record did not change, compared with the commit before it."""
    checks = {}
    if not parent:
        return checks
    before = show(parent, "parity/report.json")
    now = traceability.read(os.path.join("parity", "report.json"))
    settle = lambda text: [row for row in json.loads(text)["scenarios"]  # noqa: E731
                           if row.get("slice", row["scenario"].split("_")[0]) == "settlement"]
    checks["settlement parity rows"] = {
        "same": bool(before) and settle(before) == settle(now), "count": len(settle(now))}
    before_tr = show(parent, "docs/TRACEABILITY.md") or ""
    now_tr = traceability.read("docs/TRACEABILITY.md")
    rows = lambda text: [line for line in text.splitlines() if line.startswith("| SETTLE-")]  # noqa: E731
    checks["settlement traceability rows"] = {"same": rows(before_tr) == rows(now_tr), "count": len(rows(now_tr))}
    checks["src/main"] = {"same": git_ok("diff", "--quiet", parent, "HEAD", "--", "src/main"), "count": None}
    checks["transcripts/"] = {"same": git_ok("diff", "--quiet", parent, "HEAD", "--", "transcripts"), "count": None}
    return checks


def compute(record_rel):
    change = os.path.basename(record_rel).split("-")[0] + "-" + os.path.basename(record_rel).split("-")[1]
    intro = intro_commit(record_rel)
    parent = (intro + "^") if intro and git_ok("rev-parse", "--verify", intro + "^") else None
    return {
        "change": change, "record": record_rel,
        "introduced": intro[:7] if intro else None,
        "baseline": git("rev-parse", "--short", parent).strip() if parent else None,
        "rules": rule_versions(record_rel),
        "scenarios": scenarios(record_rel, change, parent),
        "tests": tests(change, parent),
        "files": files_changed(parent),
        "untouched": untouched(parent),
    }


def markdown(data):
    out = ["## Impact of %s" % data["change"], "", BEGIN, ""]
    base = ("Compared with `%s`, the commit before this record was added (`%s`)."
            % (data["baseline"], data["introduced"]) if data["baseline"]
            else "The record is not committed yet; the comparison baseline will be the commit before it.")
    out += [base, ""]
    out.append("**Rule versions touched**")
    out.append("")
    for rule in data["rules"] or []:
        arrow = ("%s %s → %s" % (rule["rule"], rule["from"], rule["to"]) if rule["from"]
                 else "%s %s (new version)" % (rule["rule"], rule["to"]))
        out.append("- %s (`%s`)" % (arrow, rule["spec"]))
    if not data["rules"]:
        out.append("- none: no spec rule names this record in an `Approved:` line")
    out += ["", "**Scenarios reclassified** (verdict before this record → verdict now)", ""]
    out.append("| Scenario | Before | Now | Source |")
    out.append("| --- | --- | --- | --- |")
    for row in data["scenarios"]:
        name = "`%s`" % row["scenario"] + (" (explicit scenario, own request and precondition)" if row["explicit"] else "")
        out.append("| %s | %s | %s | %s |" % (name, row["old"], row["new"], row["source"]))
    out += ["", "**Tests citing %s**" % data["change"], ""]
    for test in data["tests"]:
        out.append("- `%s` (%s, `%s`)" % (test["test"], test["state"], test["file"]))
    if not data["tests"]:
        out.append("- none")
    hand = [f for f in data["files"] if not f["generated"]]
    gen = [f for f in data["files"] if f["generated"]]
    out += ["", "**Files changed** (%d, of which %d generated)" % (len(data["files"]), len(gen)), ""]
    for item in hand:
        out.append("- `%s` (%s)" % (item["file"], item["status"]))
    if gen:
        out.append("- regenerated: %s" % ", ".join("`%s`" % f["file"] for f in gen))
    out += ["", "**Untouched**", ""]
    for name, check in data["untouched"].items():
        count = " (%d rows)" % check["count"] if check["count"] is not None else ""
        out.append("- %s: %s%s" % (name, "unchanged" if check["same"] else "CHANGED - review", count))
    out += ["", END]
    return "\n".join(out)


def update(record_path):
    record_rel = os.path.relpath(os.path.abspath(record_path), ROOT)
    data = compute(record_rel)
    text = open(record_path).read()
    block = markdown(data)
    heading = "## Impact of %s" % data["change"]
    if BEGIN in text and END in text:
        start = text.index(heading) if heading in text[:text.index(BEGIN)] else text.index(BEGIN)
        end = text.index(END) + len(END)
        text = text[:start] + block + text[end:]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    open(record_path, "w").write(text)
    return data


if __name__ == "__main__":
    paths = sys.argv[1:] or sorted(glob.glob(os.path.join(ROOT, "docs", "changes", "CHG-*.md")))
    for path in paths:
        result = update(path)
        print("impact block of %s: %d rule versions, %d scenarios, %d tests, %d files"
              % (result["change"], len(result["rules"]), len(result["scenarios"]),
                 len(result["tests"]), len(result["files"])))
